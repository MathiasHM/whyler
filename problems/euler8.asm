digit_count EQU $ - digits
window_size EQU 13
.code
PUBLIC solve
solve PROC
    lea r8, digits
    xor r9d, r9d           ; Best product
    mov r10d, digit_count - window_size + 1
next_window:
    mov eax, 1
    xor ecx, ecx
multiply_digit:
    movzx edx, byte ptr [r8+rcx]
    sub edx, '0'           ; Convert ASCII.
    imul rax, rdx          ; 9^13 fits in 64 bits only
    inc rcx
    cmp rcx, window_size
    jb multiply_digit
    cmp rax, r9
    cmova r9, rax
    inc r8
    dec r10
    jnz next_window
    mov rax, r9
    ret
solve ENDP
